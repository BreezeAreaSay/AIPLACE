//! «Двор»: role presets you can invite into the room. The original Triad lives here too, so a
//! fresh room and an invited character are built from the same material. Every preset has a
//! full persona core (the thing that makes a character a character), a starting agenda and a
//! personal project for the heartbeat to advance.

use serde::Serialize;

#[derive(Debug, Clone, Serialize)]
pub struct RolePreset {
    /// Stable id of the role (also the default agent id for the first one invited).
    pub id: &'static str,
    /// Role title: «Скептик», «Наставник»…
    pub role: &'static str,
    /// Default character name (editable when inviting).
    pub name: &'static str,
    pub archetype: &'static str,
    pub color: &'static str,
    pub glyph: &'static str,
    pub dopamine: i64,
    pub respect: i64,
    pub agenda: &'static str,
    pub core: &'static str,
    /// (id suffix, title, body) of their own project in the library.
    pub project: (&'static str, &'static str, &'static str),
    /// One line about what this role brings to the yard (UI).
    pub pitch: &'static str,
    /// Topic words that raise this character's stake in a line (lowercase stems).
    pub interests: &'static [&'static str],
}

